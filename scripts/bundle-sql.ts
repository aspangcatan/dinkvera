/**
 * Concatenates supabase/migrations/*.sql (in order) into
 * supabase/apply/schema.sql — one file to paste into the Supabase SQL
 * Editor of a fresh project. Run with `npm run db:bundle` after changing
 * a migration; the migrations stay the source of truth.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const migrationsDir = join(root, 'supabase', 'migrations')
const outDir = join(root, 'supabase', 'apply')

const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql'))
  .sort()

const header = `-- Sideline database schema — GENERATED by \`npm run db:bundle\`; do not edit.
-- Source: supabase/migrations/ (${files.length} files).
--
-- Paste the whole file into the SQL Editor of a NEW, empty Supabase
-- project and run it once. Then (optionally, dev/staging only) run
-- supabase/seed/demo_seed.sql. See docs/database.md.
`

const body = files
  .map(
    (f) =>
      `\n-- ===========================================================================\n-- ${f}\n-- ===========================================================================\n\n${readFileSync(join(migrationsDir, f), 'utf8').trim()}\n`,
  )
  .join('')

mkdirSync(outDir, { recursive: true })
writeFileSync(join(outDir, 'schema.sql'), `${header}${body}`)
console.log(`supabase/apply/schema.sql written from ${files.length} migrations`)
